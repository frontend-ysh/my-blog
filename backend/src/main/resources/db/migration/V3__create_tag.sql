create table tag (
    id   bigint generated by default as identity primary key,
    name varchar(30) not null,
    constraint uk_tag_name unique (name)
);

-- 글 하나에 태그가 여러 개, 태그 하나에 글이 여러 개(다대다)다.
-- 관계형 DB는 다대다를 직접 표현하지 못하므로, 둘을 잇는 연결 테이블을 둔다.
create table post_tag (
    -- 글이나 태그가 지워지면 연결 행도 함께 지워진다.
    post_id bigint not null references post (id) on delete cascade,
    tag_id  bigint not null references tag (id) on delete cascade,
    -- 같은 글에 같은 태그가 두 번 붙지 못한다.
    primary key (post_id, tag_id)
);

-- "이 태그가 붙은 글"을 찾을 때 쓰는 인덱스.
-- 기본 키 인덱스는 post_id가 앞에 있어서 tag_id로 시작하는 검색에는 쓰이지 못한다.
create index idx_post_tag_tag_id on post_tag (tag_id);
